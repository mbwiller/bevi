// design/beverage-icons/REVIEW.md as text: what the swipe verdicts say about
// every icon, written for the people and agents who draw the next one. Pure;
// scripts/icons/verdict-report.ts reads the files and writes the result.
//
// The output carries no date and no timestamp, so running it twice on the same
// verdicts changes nothing.
import { buildDeck, type DeckIcon, type ManifestRecord, type VerdictFiles } from './swipe-core.ts';

const person = (name: string) => name[0].toUpperCase() + name.slice(1);
const cell = (text: string) => text.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const byName = (a: DeckIcon, b: DeckIcon) => a.name.localeCompare(b.name, 'en');
const link = (icon: DeckIcon) => `[${cell(icon.name)}](portable-svg/${icon.slug}.svg)`;

function groupBy<T>(items: T[], key: (item: T) => string): Map<string, T[]> {
  const groups = new Map<string, T[]>();
  for (const item of items) groups.set(key(item), [...(groups.get(key(item)) ?? []), item]);
  return groups;
}

export function renderReport(records: ManifestRecord[], files: VerdictFiles): string {
  const { icons, counts } = buildDeck(records, files);
  const moduleOf = new Map(records.map(r => [r.slug, r.sourceModule ?? 'unknown recipe']));
  const good = icons.filter(i => i.pile === 'good').sort(byName);
  const needsWork = icons.filter(i => i.pile === 'needs-work').sort(byName);
  const unsorted = icons.filter(i => i.pile === 'unsorted').sort(byName);
  const out: string[] = [];

  out.push(
    '# Icon review: the examples to match and the icons to redraw',
    '',
    '<!-- Generated by `npm run icons:report` from verdicts/*.json and manifest.json. Do not edit by hand: sort icons with `npm run icons:swipe`, then run the report again. -->',
    '',
    `**${icons.length} icons: ${counts.good} good, ${counts['needs-work']} need work, ${counts.unsorted} not sorted yet.**`,
    '',
    '## The standard',
    '',
    'Every icon is held to the same bar, whichever batch it came in and however large that batch was.',
    '',
    '- **An icon is finished when a person has sorted it Good** in `npm run icons:swipe`. Passing `validate.mjs` and the authoring agent\'s own review make it a draft, not a finished icon.',
    '- **The Good icons below are the reference.** Before drawing a drink, open the Good examples of the same package type and match their finish: the real package shape, the brand\'s own mark and label layout, and the same detail at full size and at tile size.',
    '- **The Needs work icons are the redraw queue, and are not precedents.** Do not copy their recipe for a new drink. Fix them in the recipe module named below; a redrawn icon returns to the swipe deck on its own, labelled with the verdict it answers.',
    '- **A note says what the reviewer saw.** Where there is none, compare the icon with the nearest Good examples to find what falls short.',
    '',
  );

  const modules = [...groupBy(icons, i => moduleOf.get(i.slug)!)].map(([module, list]) => ({
    module,
    good: list.filter(i => i.pile === 'good').length,
    needsWork: list.filter(i => i.pile === 'needs-work').length,
    unsorted: list.filter(i => i.pile === 'unsorted').length,
  }));
  const withWork = modules.filter(m => m.needsWork).sort((a, b) => b.needsWork - a.needsWork || a.module.localeCompare(b.module));
  if (withWork.length) {
    out.push('## Where the work is', '', '| Recipe module | Needs work | Good | Not sorted |', '|---|---:|---:|---:|');
    for (const m of withWork) out.push(`| \`${m.module}\` | ${m.needsWork} | ${m.good} | ${m.unsorted} |`);
    const clean = modules.filter(m => !m.needsWork && !m.unsorted && m.good).length;
    out.push('', `${clean} other recipe ${clean === 1 ? 'module is' : 'modules are'} entirely Good.`, '');
  }

  out.push(`## Needs work (${needsWork.length})`, '');
  if (!needsWork.length) out.push('None.', '');
  for (const m of withWork) {
    const list = needsWork.filter(i => moduleOf.get(i.slug) === m.module);
    out.push(`### \`${m.module}\`: ${list.length} of ${m.good + m.needsWork + m.unsorted}`, '', '| | Drink | Slug | Marked by | Note |', '|---|---|---|---|---|');
    for (const i of list) out.push(`| <img src="portable-svg/${i.slug}.svg" width="56" alt=""> | ${cell(i.name)} | \`${i.slug}\` | ${person(i.by!)} | ${cell(i.note ?? '')} |`);
    out.push('');
  }

  out.push(`## Good: the reference examples (${good.length})`, '', 'Grouped by package family. Each name opens the published art.', '');
  if (!good.length) out.push('None yet.', '');
  for (const [family, list] of [...groupBy(good, i => i.family || 'unclassified')].sort((a, b) => a[0].localeCompare(b[0], 'en'))) {
    out.push(`- **${family}** (${list.length}): ${list.map(link).join(' · ')}`);
  }
  if (good.length) out.push('');

  out.push(`## Not sorted yet (${unsorted.length})`, '');
  if (!unsorted.length) out.push('None: every icon has a verdict.', '');
  else out.push(unsorted.map(i => `${link(i)}${i.previous ? ` (redrawn since ${person(i.previous.by)} marked it ${i.previous.verdict === 'good' ? 'good' : 'needs work'})` : ''}`).join(' · '), '');

  return out.join('\n');
}
