#!/usr/bin/env node
// Ship the authored beverage icons to the app. No dependencies, no network.
//
//   node scripts/icons/export-app.mjs           write app/public/bev-icons/ and the bevId -> URL map
//   node scripts/icons/export-app.mjs --check   write nothing; exit 1 when those outputs are stale
//
// Reads design/beverage-icons/manifest.json, copies each record's portable SVG (paths only, no
// fonts) byte for byte to app/public/bev-icons/<slug>.svg, removes icons no record claims, and
// writes app/src/lib/bevIcons.generated.ts. Each URL carries the first 8 hex of the SVG's sha256
// as ?v=, so a redrawn icon under the same slug busts caches. Deterministic: a second run changes
// nothing. Run it after every icon batch and commit both outputs.

import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const iconsDir = resolve(root, 'design/beverage-icons');
const manifestPath = resolve(iconsDir, 'manifest.json');
const publicDir = resolve(root, 'app/public/bev-icons');
const mapPath = resolve(root, 'app/src/lib/bevIcons.generated.ts');
const check = process.argv.includes('--check');

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;
const SLUG = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const SHA256 = /^[0-9a-f]{64}$/;

function fail(message) {
  console.error(`export-app: ${message}`);
  process.exit(1);
}

const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const rel = (p) => relative(root, p);

if (!existsSync(manifestPath)) fail(`${rel(manifestPath)} not found`);
let manifest;
try {
  manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
} catch (err) {
  fail(`${rel(manifestPath)} is not valid JSON: ${err.message}`);
}
if (!Array.isArray(manifest.records)) fail(`${rel(manifestPath)} has no records array`);

// Validate every record and load its portable SVG.
const icons = [];
const seenIds = new Map();
const seenSlugs = new Map();
for (const [i, r] of manifest.records.entries()) {
  const where = `record ${i} (${r?.slug ?? 'no slug'})`;
  if (typeof r.bevId !== 'string' || !UUID.test(r.bevId)) fail(`${where}: bevId ${JSON.stringify(r.bevId)} is not a lowercase UUID`);
  if (typeof r.slug !== 'string' || !SLUG.test(r.slug)) fail(`${where}: slug ${JSON.stringify(r.slug)} is not kebab-case`);
  if (seenIds.has(r.bevId)) fail(`duplicate bevId ${r.bevId} in ${seenIds.get(r.bevId)} and ${r.slug}`);
  if (seenSlugs.has(r.slug)) fail(`duplicate slug ${r.slug} (bevIds ${seenSlugs.get(r.slug)} and ${r.bevId})`);
  seenIds.set(r.bevId, r.slug);
  seenSlugs.set(r.slug, r.bevId);

  const source = r.assets?.portableSvg;
  const expected = r.assets?.portableSvgSha256;
  if (typeof source !== 'string') fail(`${where}: assets.portableSvg is missing`);
  if (typeof expected !== 'string' || !SHA256.test(expected)) fail(`${where}: assets.portableSvgSha256 is missing or not a sha256`);
  const sourcePath = resolve(iconsDir, source);
  if (!sourcePath.startsWith(iconsDir + '/')) fail(`${where}: ${source} points outside design/beverage-icons`);
  if (!existsSync(sourcePath)) fail(`${where}: source file ${rel(sourcePath)} not found`);
  const bytes = readFileSync(sourcePath);
  const actual = sha256(bytes);
  if (actual !== expected) fail(`${where}: ${rel(sourcePath)} has sha256 ${actual}, the manifest says ${expected}. Rebuild the icons first.`);

  icons.push({ bevId: r.bevId, slug: r.slug, name: `${r.slug}.svg`, bytes, url: `/bev-icons/${r.slug}.svg?v=${expected.slice(0, 8)}` });
}
icons.sort((a, b) => (a.bevId < b.bevId ? -1 : a.bevId > b.bevId ? 1 : 0));

const map = [
  '// Generated by scripts/icons/export-app.mjs from design/beverage-icons/manifest.json. Do not edit; re-run the script.',
  '',
  '/** Catalog bevId -> the URL of its authored icon in app/public/bev-icons/ (`?v=` is the SVG hash prefix). */',
  'export const BEV_ICONS: Readonly<Record<string, string>> = {',
  ...icons.map((icon) => `  '${icon.bevId}': '${icon.url}',`),
  '};',
  '',
].join('\n');

// Compare the wanted state with the disk.
const wanted = new Set(icons.map((icon) => icon.name));
const existing = existsSync(publicDir) ? readdirSync(publicDir) : [];
const stale = existing.filter((name) => !wanted.has(name));
const changed = icons.filter((icon) => {
  const target = resolve(publicDir, icon.name);
  return !existsSync(target) || !readFileSync(target).equals(icon.bytes);
});
const mapChanged = !existsSync(mapPath) || readFileSync(mapPath, 'utf8') !== map;

if (check) {
  const problems = [
    ...changed.map((icon) => `missing or outdated: ${rel(resolve(publicDir, icon.name))}`),
    ...stale.map((name) => `not in the manifest: ${rel(resolve(publicDir, name))}`),
    ...(mapChanged ? [`outdated: ${rel(mapPath)}`] : []),
  ];
  if (problems.length) {
    console.error(`export-app --check: the app's icons are stale. Run node scripts/icons/export-app.mjs.\n  ${problems.join('\n  ')}`);
    process.exit(1);
  }
  console.log(`export-app --check: ok (${icons.length} icons current)`);
  process.exit(0);
}

mkdirSync(publicDir, { recursive: true });
for (const name of stale) rmSync(resolve(publicDir, name), { recursive: true, force: true });
for (const icon of changed) writeFileSync(resolve(publicDir, icon.name), icon.bytes);
if (mapChanged) writeFileSync(mapPath, map);
console.log(
  `export-app: ${icons.length} icons; ${changed.length} written, ${stale.length} removed, ` +
    `${rel(mapPath)} ${mapChanged ? 'written' : 'unchanged'}`,
);
