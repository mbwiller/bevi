// ---- Tapered tumbler (clear glass, thick base), symmetric about x=100.
// top: rim plane y, rx/ry: rim ellipse, bhw: half width at the inner bottom (bot), foot: ground line.
function tumbler({top = 56, rx = 47, ry = 10, bot = 219, bhw = 32, foot = 234, surf = 64}) {
  const hw = y => rx - (y - top) * (rx - bhw) / (foot - top);
  const W = 2.4; // wall
  const outline = `M${100 - rx} ${top}A${rx} ${ry} 0 0 1 ${100 + rx} ${top}L${r2(100 + hw(foot - 5))} ${foot - 5}A${r2(hw(foot - 5))} 5 0 0 1 ${r2(100 - hw(foot - 5))} ${foot - 5}Z`;
  const a = r2(hw(surf) - W), b = r2(hw(bot) - W), sry = r2(ry * .86);
  const liquid = `M${r2(100 - a)} ${surf}A${a} ${sry} 0 0 1 ${r2(100 + a)} ${surf}L${r2(100 + b)} ${bot}A${b} 4.5 0 0 1 ${r2(100 - b)} ${bot}Z`;
  const baseTop = bot + 3.5, bb = r2(hw(baseTop) - 1.2), fb = r2(hw(foot - 5) - 1);
  const base = `M${r2(100 - bb)} ${baseTop}A${bb} 4.5 0 0 0 ${r2(100 + bb)} ${baseTop}L${r2(100 + fb)} ${foot - 5.5}A${fb} 4.6 0 0 1 ${r2(100 - fb)} ${foot - 5.5}Z`;
  return {top, rx, ry, bot, foot, surf, a, b, sry, hw, outline, liquid, base, baseTop};
}
const nearRim = (g, x) => g.top + g.ry * Math.sqrt(Math.max(0, 1 - ((x - 100) / g.rx) ** 2));

