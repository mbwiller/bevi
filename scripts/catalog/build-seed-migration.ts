/**
 * Generates the catalog seed migration from data/catalog/{categories.json,bevs.csv}.
 *
 *   npm run catalog:migration -- --new <version>  # write supabase/migrations/<version>_catalog_seed.sql
 *   npm run catalog:migration -- --check          # fail if the newest one is out of date (CI)
 *
 * Migrations are append-only once merged (supabase/CLAUDE.md): after a catalog change, generate a
 * NEW migration with `--new`, don't rewrite a merged one. The SQL is idempotent, so re-running it
 * only updates seeded rows:
 *   - categories are upserted;
 *   - each Bev's id is uuidv5(slug) (catalogBevId), so a slug always maps to the same row; it is
 *     inserted 'active', source 'seed', with no photo (the app draws placeholder art), or its catalog
 *     fields are updated, never its status;
 *   - a row whose (category, brand, name, flavor) already belongs to another live Bev (say, one a
 *     user created first) is skipped instead of failing the migration;
 *   - a row whose UPC already belongs to another Bev is skipped too;
 *   - aliases are lowercased, and an alias shared by several Bevs is skipped (bev_aliases is keyed
 *     by alias, so it can't point at all of them).
 * A later seed migration never moves or removes an existing alias (`on conflict do nothing`) and
 * never deletes a Bev whose row left the CSV: retire one with an explicit migration (status
 * 'hidden' or 'merged').
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { aliasesOf, catalogBevId, loadBevRows, loadCategories, loadFlavorProfileRows } from "./catalog.ts";

const __dirname = dirname(fileURLToPath(import.meta.url));
const MIGRATIONS_DIR = join(__dirname, "..", "..", "supabase", "migrations");
const SUFFIX = "_catalog_seed.sql";

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const qOrNull = (s: string): string => (s.trim() === "" ? "null" : q(s.trim()));

export function buildSeedSql(): string {
  const categories = loadCategories();
  const rows = loadBevRows();
  const profiles = loadFlavorProfileRows();

  const owners = new Map<string, string[]>();
  for (const row of rows) for (const a of aliasesOf(row)) owners.set(a, [...(owners.get(a) ?? []), row.slug]);
  const aliases = rows.flatMap((row) => aliasesOf(row).filter((a) => owners.get(a)!.length === 1).map((a) => ({ alias: a, slug: row.slug })));
  const skipped = [...owners].filter(([, slugs]) => slugs.length > 1).map(([a]) => a);

  // Roots first, then leaves: `parent_id` references this same table, so a
  // leaf's row cannot be inserted before the root it points at. Within each
  // half the file's own order is kept, which is sortOrder (see Category).
  const orderedCategories = [
    ...categories.filter((c) => c.parentId === null),
    ...categories.filter((c) => c.parentId !== null),
  ];
  const categoryValues = orderedCategories
    .map(
      (c) =>
        `  (${q(c.id)}, ${q(c.name)}, ${c.parentId === null ? "null" : q(c.parentId)}, ${c.sortOrder}, ${c.isAlcoholic}, ${c.emoji ? q(c.emoji) : "null"})`,
    )
    .join(",\n");

  // One row per line, the slug as a trailing comment (after the comma, so it can't swallow it).
  const bevValues = rows
    .map(
      (r, i) =>
        `  (${q(catalogBevId(r.slug))}, ${q(r.name.trim())}, ${qOrNull(r.brand)}, ${qOrNull(r.flavor)}, ${q(r.category)}, ${qOrNull(r.leaf)}, ` +
        `${Number(r.price_tier)}, ${r.price_estimated === "true"}, ${qOrNull(r.upc)}, ${r.is_starter === "true"})` +
        `${i < rows.length - 1 ? "," : ""} -- ${r.slug}`,
    )
    .join("\n");

  const aliasValues = aliases.map((a) => `  (${q(a.alias)}, ${q(catalogBevId(a.slug))})`).join(",\n");

  // Flavour profiles (A-17). Keyed by the same uuidv5(slug), so a profile
  // always lands on its Bev without a lookup.
  const profileValues = profiles
    .map(
      (p, i) =>
        `  (${q(catalogBevId(p.slug))}, ${q(p.base)}, ${p.carbonated === "true"}, ${Number(p.caffeine)}, ` +
        `${Number(p.sweetness)}, ${p.dairy === "true"}, ${p.alcohol === "true"}, ${q(p.serve)})` +
        `${i < profiles.length - 1 ? "," : ""} -- ${p.slug}`,
    )
    .join("\n");

  return `-- GENERATED by scripts/catalog/build-seed-migration.ts from data/catalog/categories.json and
-- data/catalog/bevs.csv and data/catalog/flavor-profiles.csv. Do not edit: change the catalog and
-- generate a new migration
-- (npm run catalog:migration -- --new <version>). CI checks this file against the CSV.
--
-- ${categories.length} categories, ${rows.length} Bevs (${rows.filter((r) => r.is_starter === "true").length} starters), ${aliases.length} aliases,
-- ${profiles.length} flavour profiles.
-- Skipped aliases shared by several Bevs: ${skipped.length ? skipped.join(", ") : "none"}.

set search_path = public, extensions;

insert into public.categories (id, name, parent_id, sort_order, is_alcoholic, emoji) values
${categoryValues}
on conflict (id) do update
   set name = excluded.name,
       parent_id = excluded.parent_id,
       sort_order = excluded.sort_order,
       is_alcoholic = excluded.is_alcoholic,
       emoji = excluded.emoji;

insert into public.bevs (id, name, brand, flavor, category_id, leaf_category_id, price_tier, price_estimated, upc, is_starter, status, source)
select v.id::uuid, v.name, v.brand, v.flavor, v.category_id, v.leaf_category_id, v.price_tier::smallint, v.price_estimated, v.upc, v.is_starter, 'active', 'seed'
  from (values
${bevValues}
  ) as v(id, name, brand, flavor, category_id, leaf_category_id, price_tier, price_estimated, upc, is_starter)
 where not exists (
   select 1 from public.bevs b
    where b.id <> v.id::uuid
      and b.status in ('pending_photo', 'active')
      and b.category_id = v.category_id
      and lower(coalesce(b.brand, '')) = lower(coalesce(v.brand, ''))
      and lower(b.name) = lower(v.name)
      and lower(coalesce(b.flavor, '')) = lower(coalesce(v.flavor, ''))
 )
   and not exists (
   select 1 from public.bevs b
    where b.id <> v.id::uuid and v.upc is not null and b.upc = v.upc and b.status <> 'merged'
 )
on conflict (id) do update
   set name = excluded.name,
       brand = excluded.brand,
       flavor = excluded.flavor,
       category_id = excluded.category_id,
       -- A-13: re-points a seeded Bev onto its leaf. The catalog is the source
       -- of truth for a SEEDED row, so this overwrites. A user-created Bev is
       -- never in this payload and keeps whatever it has (null until something
       -- relabels it, which a parent-level category_id makes valid).
       leaf_category_id = excluded.leaf_category_id,
       price_tier = excluded.price_tier,
       price_estimated = excluded.price_estimated,
       upc = excluded.upc,
       is_starter = excluded.is_starter,
       updated_at = now();

insert into public.bev_aliases (alias, bev_id, source)
select v.alias, v.bev_id::uuid, 'seed'
  from (values
${aliasValues}
  ) as v(alias, bev_id)
 where exists (select 1 from public.bevs b where b.id = v.bev_id::uuid)
on conflict (alias) do nothing;

-- A profile for a Bev whose row was skipped above (its natural key or UPC
-- already belonged to someone else's Bev) has nothing to attach to, so the
-- exists guard drops it rather than failing the migration -- same tactic as
-- the aliases.
insert into public.bev_flavor_profiles (bev_id, base, carbonated, caffeine, sweetness, dairy, alcohol, serve, source)
select v.bev_id::uuid, v.base, v.carbonated, v.caffeine::smallint, v.sweetness::smallint, v.dairy, v.alcohol, v.serve, 'catalog'
  from (values
${profileValues}
  ) as v(bev_id, base, carbonated, caffeine, sweetness, dairy, alcohol, serve)
 where exists (select 1 from public.bevs b where b.id = v.bev_id::uuid)
on conflict (bev_id) do update
   set base = excluded.base,
       carbonated = excluded.carbonated,
       caffeine = excluded.caffeine,
       sweetness = excluded.sweetness,
       dairy = excluded.dairy,
       alcohol = excluded.alcohol,
       serve = excluded.serve,
       source = 'catalog',
       updated_at = now();
`;
}

function newestSeedMigration(): string | null {
  const files = readdirSync(MIGRATIONS_DIR).filter((f) => f.endsWith(SUFFIX)).sort();
  return files.length ? join(MIGRATIONS_DIR, files[files.length - 1]!) : null;
}

function main(argv: string[]): void {
  const sql = buildSeedSql();
  if (argv.includes("--check")) {
    const file = newestSeedMigration();
    if (!file) {
      console.error(`catalog:migration --check: no *${SUFFIX} in supabase/migrations`);
      process.exit(1);
    }
    if (readFileSync(file, "utf8") !== sql) {
      console.error(
        `catalog:migration --check: ${file} doesn't match data/catalog. Generate a new migration:\n` +
          `  npm run catalog:migration -- --new <YYYYMMDDHHMMSS>`,
      );
      process.exit(1);
    }
    console.log(`catalog:migration --check: ${file} is up to date`);
    return;
  }
  // Only ever writes a NEW file: rewriting an existing seed migration would edit one that may
  // already be merged and applied (migrations are append-only).
  const i = argv.indexOf("--new");
  const version = i >= 0 ? (argv[i + 1] ?? "") : "";
  if (!/^\d{14}$/.test(version)) {
    console.error("usage: catalog:migration -- --new <YYYYMMDDHHMMSS> | --check");
    process.exit(1);
  }
  const file = join(MIGRATIONS_DIR, `${version}${SUFFIX}`);
  if (existsSync(file)) {
    console.error(`${file} already exists; pick a new version (migrations are append-only)`);
    process.exit(1);
  }
  writeFileSync(file, sql);
  console.log(`wrote ${file}`);
}

main(process.argv.slice(2));
