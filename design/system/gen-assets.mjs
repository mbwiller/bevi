// ---- Wordmark (Fredoka Bold, OFL; tittle replaced by two fizz bubbles) ----
const toAB = (b) => b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength);
const font = opentype.parse(toAB(fs.readFileSync(path.join(NM, '@fontsource/fredoka/files/fredoka-latin-700-normal.woff'))));
const U = font.unitsPerEm;
const track = -18;
let x = 0, prev = null, iX = 0;
const letterPaths = [];
for (const ch of ['b', 'e', 'v', 'i']) {
  const g = font.charToGlyph(ch);
  if (prev) x += font.getKerningValue(prev, g) + track;
  const p = g.getPath(x, 0, U);
  if (ch === 'i') {
    iX = x;
    const keep = []; let cur = [];
    for (const c of p.commands) {
      cur.push(c);
      if (c.type === 'Z') { const ys = cur.filter((k) => k.y !== undefined).map((k) => k.y); if (Math.min(...ys) > -520) keep.push(...cur); cur = []; }
    }
    p.commands = keep;
  }
  letterPaths.push(p.toPathData(1));
  x += g.advanceWidth; prev = g;
}
const bubble = { cx: +(iX + 125.5).toFixed(1), cy: -655, r: 104 };
const fizz = { cx: +(bubble.cx + 118).toFixed(1), cy: bubble.cy - 150, r: 44 };
const minY = fizz.cy - fizz.r - 6;
const vb = [-4, Math.floor(minY), Math.ceil(Math.max(x, fizz.cx + fizz.r) + 8), Math.ceil(12 - minY)];
const letters = letterPaths.join('');
const WM = { viewBox: vb.join(' '), w: vb[2], h: vb[3], letters, bubble, fizz };
fs.writeFileSync(path.join(ROOT, 'src/wordmark.generated.js'), '// Generated by gen-assets.mjs from Fredoka Bold (OFL). Do not edit.\nexport const WORDMARK = ' + JSON.stringify(WM) + ';\n');

const wordmarkSvg = (ink, fz) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${WM.viewBox}" width="${Math.round(WM.w / 10)}" height="${Math.round(WM.h / 10)}" role="img" aria-label="bevi"><path fill="${ink}" d="${letters}"/><circle fill="${fz}" cx="${bubble.cx}" cy="${bubble.cy}" r="${bubble.r}"/><circle fill="${fz}" cx="${fizz.cx}" cy="${fizz.cy}" r="${fizz.r}"/></svg>\n`;
fs.mkdirSync(path.join(ROOT, 'out/Logos'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'out/Logos/wordmark.svg'), wordmarkSvg('#4a2a84', '#1494a8'));
fs.writeFileSync(path.join(ROOT, 'out/Logos/wordmark-dark.svg'), wordmarkSvg('#b9a4f2', '#5fd6e6'));
fs.writeFileSync(path.join(ROOT, 'out/Logos/wordmark-white.svg'), wordmarkSvg('#ffffff', '#5fd6e6'));

// App icon: grape square, white "b" from the same face, the two fizz bubbles. 1024 canvas; iOS applies the mask.
const gb = font.charToGlyph('b');
const bb = gb.getBoundingBox();
const s = 0.78; // glyph scale: b is ~0.73em tall -> ~570px
const bw = (bb.x2 - bb.x1) * s, bh = (bb.y2 - bb.y1) * s;
const ox = 470 - ((bb.x1 + bb.x2) / 2) * s, oy = 530 + ((bb.y1 + bb.y2) / 2) * s; // glyph centred a little left/low of centre; oy = baseline
const bPath = gb.getPath(ox, oy, U * s).toPathData(1);
const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024" role="img" aria-label="Bevi app icon"><rect width="1024" height="1024" fill="#4a2a84"/><path fill="#ffffff" d="${bPath}"/><circle fill="#5fd6e6" cx="${Math.round(ox + bb.x2 * s + 80)}" cy="${Math.round(oy - bb.y2 * s + 40)}" r="70"/><circle fill="#5fd6e6" cx="${Math.round(ox + bb.x2 * s + 158)}" cy="${Math.round(oy - bb.y2 * s - 86)}" r="32"/></svg>\n`;
fs.writeFileSync(path.join(ROOT, 'out/Logos/app-icon.svg'), iconSvg);
